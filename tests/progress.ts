import assert from 'node:assert/strict';
import {ProgressTracker,SAVE_KEY} from '../src/progress/tracker';
import {Game} from '../src/gameplay/game';

const memory=new Map<string,string>();
const make=()=>new ProgressTracker(k=>memory.get(k)??null,(k,v)=>{memory.set(k,v);return true;});
const progress=make();
const game=new Game();game.onProgress=(type,payload,critical)=>progress.emit(type,payload,critical);
game.start();game.director.disabled=true;
assert.equal(progress.data.stats.totalRuns,1);
assert.equal(progress.data.chapters['sunset-valley'].entries,1);
assert.equal(progress.data.chapters['bamboo-sea'],undefined);
const target=game.spawn('ink',{x:460,y:665})!;
assert.ok(game.cast('line'));
game.update(.25);
assert.equal(progress.data.stats.totalSuccessfulCasts,1);
assert.equal(progress.data.spells.line.casts,1);
assert.equal(progress.data.firstDrawnGlyphs.line.length<=48,true);
assert.equal(progress.data.enemies.ink.kills,1);
assert.equal(progress.data.spells.line.kills,1);
assert.ok(progress.data.spells.line.damage>=40);
assert.equal(progress.data.enemies.ink.firstKillChapter,'sunset-valley');
assert.equal(game.enemies.some(e=>e.id===target.id),false);
game.menu();
assert.equal(progress.data.recentRuns[0].result,'abandoned');
assert.equal(progress.data.stats.totalRuns,1);
const restored=make();
assert.equal(restored.data.stats.totalKills,1);
assert.equal(restored.data.spells.line.casts,1);
restored.emit('RUN_STARTED',{chapterId:'sunset-valley'});
restored.emit('CHAPTER_ENTERED',{chapterId:'sunset-valley'});
restored.emit('CHAPTER_CLEARED',{chapterId:'sunset-valley',seconds:180,score:500});
restored.emit('CHAPTER_CLEARED',{chapterId:'sunset-valley',seconds:180,score:500});
restored.emit('RUN_ENDED',{result:'win',seconds:180,score:500});
restored.emit('RUN_ENDED',{result:'win',seconds:180,score:500});
assert.equal(restored.data.stats.totalChapterClears,1);
assert.equal(restored.data.recentRuns.length,2);
assert.equal(restored.data.achievements.firstClear.completedAt!==undefined,true);
assert.equal(restored.data.achievements.allChapters,undefined);
const tutorialStore=new Map<string,string>();
const tutorialProgress=new ProgressTracker(k=>tutorialStore.get(k)??null,(k,v)=>{tutorialStore.set(k,v);return true;});
const tutorial=new Game();tutorial.onProgress=(type,payload,critical)=>tutorialProgress.emit(type,payload,critical);
tutorial.start(true);tutorial.director.disabled=true;
tutorial.spawn('ink',{x:460,y:665});assert.ok(tutorial.cast('line'));tutorial.update(.25);
tutorial.time=tutorial.duration-.05;tutorial.bossDead=true;tutorial.update(.1);
assert.equal(tutorial.state,'win');
assert.equal(tutorialProgress.data.stats.totalRuns,0);
assert.equal(tutorialProgress.data.stats.totalKills,0);
assert.equal(tutorialProgress.data.stats.totalChapterClears,0);
assert.equal(Object.keys(tutorialProgress.data.chapters).length,0);
assert.equal(tutorialProgress.data.spells.line,undefined);
assert.equal(tutorialProgress.data.enemies.ink,undefined);
assert.equal(tutorialProgress.data.recentRuns.length,0);
tutorial.start();assert.equal(tutorialProgress.data.stats.totalRuns,1);
assert.equal(tutorialProgress.data.chapters['sunset-valley'].entries,1);
memory.set(SAVE_KEY,'{broken');
const recovered=make();
assert.equal(recovered.data.stats.totalRuns,0);
assert.equal(recovered.saveFailed,false);
const fail=new ProgressTracker(()=>null,()=>false);
assert.equal(fail.saveFailed,true);
console.log('PASS: progress events, tutorial isolation, restore, chapter idempotency, unavailable achievements, corrupt storage, save failure');
