import assert from 'node:assert/strict';
import {chromium} from '@playwright/test';
import fs from 'node:fs';
const browser=await chromium.launch({headless:true,executablePath:process.env.CHROME_PATH||'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe'});
const page=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:5175/?qa=1',{waitUntil:'networkidle'});
await page.waitForFunction(()=>!!window.__LINGHU__);
fs.mkdirSync('screenshots/home',{recursive:true});
const shot=async name=>page.locator('#app canvas').screenshot({path:`screenshots/home/${name}.png`});
const click=async action=>{
 const point=await page.evaluate(action=>{const {view,app}=window.__LINGHU__;const z=view.ui.zones.find(z=>z.action===action);if(!z)throw Error(`Missing ${action}`);const rect=app.canvas.getBoundingClientRect();const p=app.stage.toGlobal({x:z.x+z.w/2,y:z.y+z.h/2});return {x:rect.x+p.x*rect.width/app.screen.width,y:rect.y+p.y*rect.height/app.screen.height};},action);
 await page.mouse.click(point.x,point.y);await page.waitForTimeout(180);
};
await shot('menu-mobile');
await click('settings');await click('sound');
assert.equal(await page.evaluate(()=>window.__LINGHU__.view.ui.menuPanel),'settings');
await click('quality');await shot('settings');await click('closePanel');
await click('profile');await click('cultivate');await shot('profile');
await click('archive');assert.equal(await page.evaluate(()=>window.__LINGHU__.archive.visible),true);
await page.keyboard.press('Escape');await click('closePanel');
await click('profile');await click('achievements');assert.equal(await page.evaluate(()=>window.__LINGHU__.archive.visible),true);
await page.keyboard.press('Escape');await click('journal');assert.equal(await page.evaluate(()=>window.__LINGHU__.archive.visible),true);
await page.keyboard.press('Escape');await click('closePanel');await click('practice');
assert.equal(await page.evaluate(()=>window.__LINGHU__.game.practice),true);
await page.evaluate(()=>window.__LINGHU__.action('menu'));await page.waitForTimeout(100);
await click('endless');assert.equal(await page.evaluate(()=>window.__LINGHU__.game.endless),true);
await page.evaluate(()=>window.__LINGHU__.action('restart'));
assert.equal(await page.evaluate(()=>window.__LINGHU__.game.endless),true);
await page.evaluate(()=>window.__LINGHU__.action('menu'));await page.waitForTimeout(100);
await click('start');assert.equal(await page.evaluate(()=>window.__LINGHU__.game.duration),180);
await page.evaluate(()=>window.__LINGHU__.action('menu'));await page.waitForTimeout(100);
await page.setViewportSize({width:450,height:800});await page.waitForTimeout(200);await shot('menu-standard');
assert.deepEqual(errors,[]);await browser.close();
console.log('PASS: mobile menu, settings persist, profile, archive, achievements and all three play modes');
