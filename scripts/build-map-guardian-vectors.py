def pack(d):
 result=bytearray();last=[0,0];axis=0;ops={'M':0,'L':1,'C':2,'Q':3,'Z':4}
 for token in re.findall(r'[A-Za-z]|-?\d+(?:\.\d+)?',d):
  if token in ops:result.append(ops[token]);axis=0;continue
  v=round(float(token)*8);delta=v-last[axis];last[axis]=v;axis=1-axis
  n=delta*2 if delta>=0 else -delta*2-1
  while n>=128:result.append((n&127)|128);n>>=7
  result.append(n)
 return base64.b64encode(result).decode('ascii')
